const fs = require('fs');
const cp = require('child_process');
const crypto = require('crypto');
const path = require('path');
const root = path.resolve(__dirname, '../../../..');
const target = '_drafts/carta-aberta-hierarquia-romanda-na-igreja';
const base = fs.readFileSync(path.join(root, target));
const dest = path.join(__dirname, 'base-atual.md');
if (fs.existsSync(dest)) throw Error('Snapshot já existe; não sobrescrever');
const old = cp.execFileSync('git', ['show', 'd083967773:' + target], {cwd: root, encoding: 'utf8'});
const header = old.slice(0, old.indexOf('-->') + 3);
if (!header.startsWith('<!--') || !header.includes('## 8. Critério final')) throw Error('Cabeçalho incompleto');
fs.writeFileSync(dest, base);
fs.writeFileSync(path.join(__dirname, 'cabecalho-historico.md'), header + '\n');
fs.writeFileSync(path.join(__dirname, 'base-retomada.json'), JSON.stringify({head:cp.execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),target,sha256:crypto.createHash('sha256').update(base).digest('hex'),headerSource:'d083967773',headerSha256:crypto.createHash('sha256').update(header).digest('hex')},null,2)+'\n');
const statePath = path.join(root,'.ia.rules/state/continue.ia');
let state = fs.readFileSync(statePath,'utf8');
state = state.replace(/FT-112\|[^\r\n]+/, 'FT-112|nome=Revisão integral da carta aberta|escopo=negocio|status=em_execucao|autorizacao=humana|retomada=2026-10-10');
state = state.replace('pendencias=Sem pendência técnica; aprovação autoral posterior.', 'pendencias=Revisão reaberta por redução retórica; executar microtarefas em .ia.rules/state/contexts/FT-112/retomada.md.\ncontexto=.ia.rules/state/contexts/FT-112/retomada.md');
fs.writeFileSync(statePath,state);
const master = path.join(__dirname,'master.md');
fs.appendFileSync(master,'\n## Retomada em 2026-10-10\n\nA conclusão acima é histórica. Revisão reaberta pelo autor: base atual restaurada, seção 6 incluída e intensidade integral. Estado e plano atuais: [retomada.md](retomada.md); histórico: [historico-retomada.md](historico-retomada.md).\n');
const plan = path.join(__dirname,'retomada.md');
fs.writeFileSync(plan,fs.readFileSync(plan,'utf8').replace('1. [em execução]','1. [concluída]').replace('cabeçlho','cabeçalho'));
console.log('Base, cabeçalho e retomada preservados.');
